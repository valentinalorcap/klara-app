async function fetchSet(prefix, names) {
  const url = `https://api.iconify.design/${prefix}.json?icons=${names.join(',')}`;
  const data = await getJSON(url);
  if (data.not_found?.length) {
    throw new Error(`${prefix}: not found -> ${data.not_found.join(', ')}`);
  }
  const dw = data.width ?? 24;
  const dh = data.height ?? 24;
  const out = {};
  for (const name of names) {
    const icon = data.icons[name];
    const w = icon.width ?? dw;
    const h = icon.height ?? dh;
    out[`${prefix}:${name}`] = { body: icon.body, viewBox: `0 0 ${w} ${h}` };
  }
  return out;
}

const merged = {};
for (const [prefix, names] of Object.entries(SETS)) {
  Object.assign(merged, await fetchSet(prefix, names));
}

const entries = Object.entries(merged)
  .map(
    ([k, v]) =>
      `  ${JSON.stringify(k)}: { body: ${JSON.stringify(v.body)}, viewBox: ${JSON.stringify(v.viewBox)} },`,
  )
  .join('\n');

const banner = `// AUTO-GENERATED by scripts/gen-product-icons.mjs — do not edit by hand.
// Inlined SVGs for the curated product-icon palette (Tabler + Lucide via Iconify),
// baked so the PWA renders them offline with zero runtime deps.
`;

const file = `${banner}
export type IconSvg = { body: string; viewBox: string };

export const ICON_SVGS: Record<string, IconSvg> = {
${entries}
};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, file);
console.log(`Wrote ${Object.keys(merged).length} icons -> ${OUT}`);
