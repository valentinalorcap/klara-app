// PWA renders icons fully offline (no Iconify runtime / no network).
//
// Source sets: Tabler (base) + Lucide (gap fillers), pulled once from the
// Iconify API. To change the palette, edit the lists below and re-run:
//
//   node scripts/gen-product-icons.mjs
//
// Output: src/lib/productIcons.generated.ts

import { writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { get } from 'node:https';

function getJSON(url) {
  return new Promise((resolve, reject) => {
    get(url, (res) => {
      if (res.statusCode !== 200) {
        reject(new Error(`HTTP ${res.statusCode} for ${url}`));
        res.resume();
        return;
      }
      let body = '';
      res.setEncoding('utf8');
      res.on('data', (c) => (body += c));
      res.on('end', () => {
        try {
          resolve(JSON.parse(body));
        } catch (e) {
          reject(e);
        }
      });
    }).on('error', reject);
  });
}

